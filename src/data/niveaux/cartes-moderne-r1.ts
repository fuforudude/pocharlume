// Les chemins dits « mobiles » s'ouvrent ou se ferment pendant la partie (événements du plan, plan-moderne-r1.ts) : leurs cases ne sont
// pas dans les cases interdites du niveau, le moteur les interdit toujours. Le décor a été placé par un script jetable (hors chemins,
// hors cases des foules et de la scène), à retoucher ici.
